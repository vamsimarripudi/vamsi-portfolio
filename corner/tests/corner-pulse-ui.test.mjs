import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {feedPage,footer} from '../src/ui.mjs';
import {nowHistoryPage} from '../src/v3-memories-ui.mjs';
const read=name=>fs.readFileSync(new URL('../public/'+name,import.meta.url),'utf8');
test('Empty Builds collection has one visible heading, no duplicate/fake content or giant decorative icon',()=>{
 const html=feedPage({active:'Builds',posts:[]});
 assert.match(html,/class="category-hero"/);
 assert.match(html,/<h1>Builds<span>\.<\/span><\/h1>/);
 assert.match(html,/class="corner-empty-collection"/);
 assert.match(html,/Nothing published here yet/);
 assert.match(html,/id="feed-heading" class="sr-only"/);
 assert.doesNotMatch(html,/<h2 id="feed-heading">Builds<\/h2>/);
 assert.doesNotMatch(html,/class="empty-feed"/);
 assert.doesNotMatch(html,/class="about-stripe"/);
 assert.doesNotMatch(html,/YOU’VE CAUGHT UP/);
});
test('Pulse has a unique ephemeral time trace, no fake live dot when idle',()=>{
 const future=new Date(Date.now()+86400000).toISOString();
 const status={label:'Learning a new thing',detail:'Today only',expiresAt:future,updatedAt:new Date().toISOString()};
 const home=feedPage({posts:[],status});
 assert.match(home,/data-corner-pulse-card/);
 assert.match(home,/data-pulse-expires=/);
 assert.match(home,/data-pulse-header-label/);
 assert.match(home,/corner-pulse-timeline/);
 assert.match(home,/Learning a new thing/);
 const now=nowHistoryPage(null,status);
 assert.match(now,/CORNER PULSE \/ FOR THIS DAY ONLY/);
 assert.match(now,/Today only/);
 assert.doesNotMatch(now,/Earlier updates/);
 const idle=nowHistoryPage(null,null);
 assert.doesNotMatch(idle,/Today only/);
 assert.match(idle,/No Pulse right now/);
});
test('Owner UI describes 24-hour expiry and supports immediate hiding',()=>{
 const admin=read('admin.js'),css=read('v6-pulse.css'),js=read('v6-pulse.js');
 assert.match(admin,/Share Pulse for 24 hours/);
 assert.match(admin,/action:'status.save'/);
 assert.match(admin,/data\.durationHours!==24/);
 assert.match(admin,/uncheck to end it/);
 assert.match(css,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
 assert.match(css,/footer-links a\[hidden\]/);
 assert.match(css,/prefers-reduced-motion:reduce/);
 assert.match(js,/Date\.parse\(pulse\?\.expiresAt/);
 assert.match(js,/window\.CornerPulse/);
 assert.doesNotMatch(js,/localStorage|sendBeacon|fetch\(/);
 assert.match(footer(),/class="corner-footer-profile"/);
});
