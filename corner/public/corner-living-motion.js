/* Quietly Alive — nonessential motion only. Never intercept links, gestures, forms or navigation. */
(()=>{
 'use strict';
 const root=document.documentElement;
 const reduced=window.matchMedia?.('(prefers-reduced-motion: reduce)');
 const minimal=()=>Boolean(reduced?.matches||root.classList.contains('ss-reduced-motion')||window.CornerMotionPolicy?.isReduced?.());
 const host=document.querySelector('main#content');
 if(host&&(host.querySelector('.corner-home-hero')||host.classList.contains('stories-corner-main'))){
   host.classList.add('corner-motion-host');
   if(!host.querySelector('.corner-ambient-layers')){
     const atmosphere=document.createElement('div');atmosphere.className='corner-ambient-layers';
     atmosphere.setAttribute('aria-hidden','true');atmosphere.innerHTML='<span></span><span></span><span></span>';
     host.prepend(atmosphere);
   }
 }
 const reveal=[...document.querySelectorAll('.sb-book-card,.sb-book-hero,.sb-toc-section,.sb-empty')];
 if(!minimal()&&'IntersectionObserver' in window&&reveal.length){
   const observer=new IntersectionObserver(entries=>{
      for(const entry of entries){if(entry.isIntersecting){entry.target.dataset.cornerVisible='true';observer.unobserve(entry.target);}}
   },{threshold:0.08,rootMargin:'0px 0px 36px 0px'});
   for(const [i,item] of reveal.entries()){
     item.dataset.cornerReveal='true';item.style.setProperty('--corner-stagger',String(i%6));
     observer.observe(item);
   }
   root.dataset.cornerRevealReady='true';
 }else for(const item of reveal)item.dataset.cornerVisible='true';
 const visibility=()=>root.classList.toggle('corner-motion-paused',document.hidden);
 document.addEventListener('visibilitychange',visibility,{passive:true});visibility();
 // Watch only genuine success notifications generated by the existing Studio handlers.
 document.addEventListener('corner:stories:confirmed',event=>{
   if(minimal())return;
   const action=event.detail?.action;
   const target=action==='published'?document.querySelector('#ssCountPublished'):
     document.querySelector('#ssAutosaveNote,#ssSaveState');
   if(!target)return;
   target.removeAttribute('data-corner-confirmed');
   void target.offsetWidth;target.dataset.cornerConfirmed=action==='published'?'published':'saved';
   target.addEventListener('animationend',()=>target.removeAttribute('data-corner-confirmed'),{once:true});
 },{passive:true});
})();
